/**
 * @file gen_tables.cpp
 * @brief Host-side generator for the framework's lookup tables.
 *
 * WHY THIS EXISTS:
 * Many DSP modules read curves from lookup tables (a sine cycle, decay-time
 * curves, wavefolder transfer curves). On a desktop you can compute those
 * at start-up, but on the Black Pill that would cost precious RAM: a table
 * filled at run time lives in RAM (64 KB total), while a `const` table
 * written into the source lives in flash (256 KB, mostly free).
 *
 * So, like Emilie Gillet's own Python scripts for the Mutable Instruments
 * firmware, we compute the tables once on the computer and write them out
 * as C++ source. This program does exactly that, using the same formulas
 * as Partials (and therefore Gillet's originals), so the ported modules
 * sound identical.
 *
 * USAGE (from the repository root):
 *   clang++ -std=c++14 -O2 -o /tmp/gen_tables tools/gen_tables.cpp
 *   /tmp/gen_tables src/buddhabox
 *
 * It overwrites:
 *   src/buddhabox/core/lut_sine.h      — one sine cycle (+ cosine quarter)
 *   src/buddhabox/core/luts.h          — physical-model and envelope curves
 *   src/buddhabox/fx/lut_wavefolder.h  — Plaits' two wavefolder curves
 *   src/buddhabox/mod/lut_slope.h      — Tides' shape and fold curves
 *
 * HOW THE OUTPUT WORKS:
 * Each table is a `static const float` array inside an `inline` function.
 * - `static const` + a constant initializer means the linker puts the data
 *   in flash (.rodata) with no start-up code at all.
 * - `inline` lets every .cpp file include the header; the linker keeps one
 *   copy, and drops the table entirely if nothing calls the function.
 */

#include <algorithm>
#include <cmath>
#include <cstdio>
#include <string>
#include <vector>

namespace {

const double kPi = 3.14159265358979323846;

/** Write `values` as a brace-enclosed list, four per line (fits 80 columns). */
void writeValues(FILE *f, const std::vector<double> &values,
                 const char *indent) {
  for (size_t i = 0; i < values.size(); ++i) {
    if (i % 4 == 0)
      fprintf(f, "%s", indent);
    fprintf(f, "%.8ef,", values[i]);
    fprintf(f, (i % 4 == 3 || i + 1 == values.size()) ? "\n" : " ");
  }
}

/** Write one 1-D table as an inline accessor function. */
void writeTable(FILE *f, const char *doc, const char *name,
                const std::vector<double> &values) {
  fprintf(f, "%s\ninline const float *%s() {\n", doc, name);
  fprintf(f, "  static const float kTable[%zu] = {\n", values.size());
  writeValues(f, values, "      ");
  fprintf(f, "  };\n  return kTable;\n}\n\n");
}

FILE *openHeader(const std::string &path, const char *file, const char *brief) {
  FILE *f = fopen(path.c_str(), "w");
  if (!f) {
    perror(path.c_str());
    exit(1);
  }
  fprintf(f,
          "/**\n * @file %s\n * @brief %s\n *\n"
          " * GENERATED by tools/gen_tables.cpp — do not edit by hand.\n"
          " * Re-run the generator instead (see its header for usage).\n"
          " *\n * Derived from the lookup-table scripts of Mutable "
          "Instruments' Plaits,\n * Rings, Elements, Peaks, Streams and "
          "Tides, Copyright 2013-2017\n * Emilie Gillet. MIT licence.\n"
          " */\n\n#pragma once\n\nnamespace bb {\n\n",
          file, brief);
  return f;
}

void closeHeader(FILE *f) {
  fprintf(f, "} // namespace bb\n");
  fclose(f);
}

// ── core/lut_sine.h ─────────────────────────────────────────────────────

void writeSine(const std::string &dir) {
  FILE *f = openHeader(dir + "/core/lut_sine.h", "lut_sine.h",
                       "One cycle of sin(), stored in flash.");
  fprintf(f, "/** Steps per sine cycle (a power of two). */\n"
             "constexpr int kSineTableSize = 512;\n\n");
  // 512 steps + a quarter cycle + 2 guard points: cosine can be read at an
  // offset of 128 without wrapping, and a read at index 1.0 is safe.
  std::vector<double> v;
  for (int i = 0; i < 512 + 128 + 2; ++i)
    v.push_back(std::sin(2.0 * kPi * i / 512.0));
  writeTable(f,
             "/**\n * sin(2*pi*i/512) for i = 0..641: one full cycle, plus a "
             "quarter cycle\n * and two guard points so a cosine read "
             "(phase + 0.25) never wraps.\n * Read it with interpolate() "
             "or sineFromPhase().\n */",
             "lutSine", v);
  closeHeader(f);
}

// ── core/luts.h ─────────────────────────────────────────────────────────

/** 257 entries (index 0..1 in 256 steps) plus one guard entry. */
std::vector<double> lut257(double (*fn)(double)) {
  std::vector<double> v;
  for (int i = 0; i < 257; ++i)
    v.push_back(fn(i / 256.0));
  v.push_back(v.back());
  return v;
}

double fourDecades(double x) { return std::pow(10.0, 4.0 * x); }

double stiffness(double g) {
  if (g < 0.25)
    return -(0.25 - g) * 0.25;
  if (g < 0.3)
    return 0.0;
  if (g < 0.9)
    return 0.01 * std::pow(10.0, (g - 0.3) / 0.6 * 2.005) - 0.01;
  double h = (g - 0.9) / 0.1;
  return 1.5 - std::cos(h * h * kPi) / 2.0;
}

double expoCurve(double x) {
  return (1.0 - std::exp(-4.0 * x)) / (1.0 - std::exp(-4.0));
}

double quarticCurve(double x) { return std::pow(x, 3.32); }

double gompertzRaw(double x) {
  double y = std::exp(-10.0 * std::exp(-13.0 * x));
  return y + 0.1 * std::pow(y, 0.05);
}

double gompertz(double x) {
  return (gompertzRaw(x) - gompertzRaw(0.0)) /
         (gompertzRaw(1.0) - gompertzRaw(0.0));
}

void writeLuts(const std::string &dir) {
  FILE *f = openHeader(dir + "/core/luts.h", "luts.h",
                       "Shared curves for physical models, envelopes and "
                       "the vactrol.");
  writeTable(f,
             "/**\n * 10^(4x) for x = 0..1 (257 entries + guard): a "
             "four-decade (1..10000)\n * exponential curve. Maps a 0..1 knob "
             "onto a wide range such as a\n * resonator's Q. Read with "
             "interpolate(lut4Decades(), x, 256.0f).\n */",
             "lut4Decades", lut257(fourDecades));

  std::vector<double> s = lut257(stiffness);
  s[255] = s[256] = s[257] = 2.0;
  writeTable(f,
             "/**\n * Partial \"stiffness\" against a resonator's structure "
             "knob (0..1):\n * negative below 0.25 (bell-like, squeezed "
             "partials), zero for\n * 0.25..0.3 (harmonic string), rising "
             "above (bars, plates, metal).\n */",
             "lutStiffness", s);

  std::vector<double> shift;
  for (int i = 0; i < 257; ++i) {
    double ratio = std::pow(2.0, i / 12.0);
    shift.push_back(2.0 * std::atan(1.0 / ratio) / (2.0 * kPi));
  }
  shift.push_back(shift.back());
  writeTable(f,
             "/**\n * Phase delay of a string's damping low-pass, indexed by "
             "its cutoff in\n * semitones above the string's pitch (0..256; "
             "read with size 1.0).\n * The string shortens its loop by this "
             "much so it stays in tune.\n */",
             "lutSvfShift", shift);

  writeTable(f,
             "/**\n * Exponential segment curve (1 - e^-4x) / (1 - e^-4) for "
             "x = 0..1:\n * fast then slow, as in Peaks' envelopes. Read with "
             "size 256.0f.\n */",
             "lutEnvExpo", lut257(expoCurve));
  writeTable(f,
             "/**\n * Quartic-ish segment curve x^3.32 for x = 0..1: slow then "
             "fast, as in\n * Peaks' ADSR attack. Read with size 256.0f.\n */",
             "lutEnvQuartic", lut257(quarticCurve));
  writeTable(f,
             "/**\n * Vactrol light-to-gain curve (a Gompertz S-curve), "
             "normalised to\n * 0..1 for x = 0..1. From Streams. Read with "
             "size 256.0f.\n */",
             "lutGompertz", lut257(gompertz));
  closeHeader(f);
}

// ── fx/lut_wavefolder.h ─────────────────────────────────────────────────

double deadband(double vIn, double rIn, double rLoad) {
  const double rFb = 150.0e3, vSat = 10.47;
  double vOut = -rFb / rIn * vIn;
  if (vOut >= vSat)
    vOut = vSat;
  if (vOut < -vSat)
    vOut = -vSat;
  return (vIn * rFb * rLoad + vOut * rIn * rLoad) /
         (rFb * rLoad + rIn * rLoad + rIn * rFb);
}

void writeWavefolder(const std::string &dir) {
  FILE *f = openHeader(dir + "/fx/lut_wavefolder.h", "lut_wavefolder.h",
                       "Plaits' two wavefolder transfer curves.");
  const int size = 512, n = size + 4;
  std::vector<double> x(n), fold(n), fold2(n);
  for (int i = 0; i < n; ++i)
    x[i] = i / (size / 2.0) - 1.0;
  x[n - 1] = x[n - 2];
  double maxAbs = 0.0, maxOut = -1e30;
  for (int i = 0; i < n; ++i) {
    double sine = std::sin(8.0 * kPi * x[i]);
    double window = std::exp(-x[i] * x[i] * 4.0);
    window *= window;
    fold[i] = sine * window + std::atan(3.0 * x[i]) * (1.0 - window);
    maxAbs = std::max(maxAbs, std::fabs(fold[i]));
    double vIn = x[i] * 12.0;
    double s1 = deadband(vIn, 10e3, 100e3);
    double s2 = deadband(vIn, 49.9e3, 44.2e3);
    double s3 = deadband(vIn, 91e3, 18e3);
    double s4 = deadband(vIn, 30e3, 71.4e3);
    double s5 = deadband(vIn, 68e3, 33.0e3);
    double s45 = -33.0 / 71.4 * s4 - 33.0 / 33.0 * s5 - 33.0 / 240.0 * vIn;
    double v = -150.0 / 100.0 * s1 - 150.0 / 44.2 * s2 - 150.0 / 18.0 * s3 -
               150.0 / 33.0 * s45;
    fold2[i] = 0.7 * v / (0.3 + std::fabs(v));
    maxOut = std::max(maxOut, fold2[i]);
  }
  for (int i = 0; i < n; ++i) {
    fold[i] /= maxAbs;
    fold2[i] /= maxOut;
  }
  writeTable(f,
             "/**\n * Sine-based fold curve (516 entries: 512 steps plus "
             "Hermite guard\n * points). Read at lutFoldSine() + 1 with "
             "interpolateHermite(..., 512).\n */",
             "lutFoldSine", fold);
  writeTable(f,
             "/**\n * Analog (Buchla 259-style op-amp and diode) fold curve, "
             "same layout\n * as lutFoldSine().\n */",
             "lutFoldAnalog", fold2);
  closeHeader(f);
}

// ── mod/lut_slope.h ─────────────────────────────────────────────────────

/** Tides stored its shapes as 16-bit integers; round the same way. */
double q16(double v) { return std::round(v * 32767.0) / 32768.0; }

void writeSlope(const std::string &dir) {
  FILE *f = openHeader(dir + "/mod/lut_slope.h", "lut_slope.h",
                       "Tides 2's waveshape and fold curves for Slope.");
  std::vector<std::vector<double>> shape(12, std::vector<double>(1025));
  // 1. Audio-rate shapers (monotonic): tables 0-4.
  double tanScale = std::atan(8.0);
  for (int i = 0; i < 1024; ++i) {
    double x = i / 1024.0;
    double fadeCrop = std::min(1.0, 4.0 - 4.0 * x);
    double bump = (1.0 - std::cos(kPi * x * 1.5)) *
                  (1.0 - std::cos(kPi * fadeCrop)) / 4.5;
    double inverseSin = std::acos(1.0 - 2.0 * x) / kPi;
    double inverseTan =
        i == 0 ? 0.0
               : std::acos(std::tan(tanScale * (1.0 - 2.0 * x)) / 8.0) / kPi;
    double v[5] = {inverseTan, inverseSin, x, 0.5 - 0.5 * std::cos(x * kPi),
                   bump};
    for (int k = 0; k < 5; ++k)
      shape[k][i] = q16(v[k]);
  }
  for (int k = 0; k < 5; ++k)
    shape[k][1024] = shape[k][1023];
  // 2. Control-rate shapes (rise, then fall): tables 5-11.
  double expoMax = 1.0 - std::exp(-5.0 * 511.0 / 512.0);
  for (int i = 0; i < 512; ++i) {
    double x = i / 512.0;
    double expo = (1.0 - std::exp(-5.0 * x)) / expoMax;
    double lg = std::log(1.0 - x * expoMax) / -5.0;
    double inverseSin = std::acos(1.0 - 2.0 * x) / kPi;
    double sine = (1.0 - std::cos(kPi * x)) / 2.0;
    const double curves[7] = {lg, lg, inverseSin, x, sine, expo, expo};
    const bool flips[7] = {false, true, false, false, false, true, false};
    for (int k = 0; k < 7; ++k) {
      shape[5 + k][i] = q16(curves[k]);
      if (!flips[k])
        shape[5 + k][513 + i] = q16(1.0 - curves[k]);
    }
  }
  for (int k = 0; k < 7; ++k) {
    shape[5 + k][512] = q16(1.0);
    if (k == 1 || k == 5)
      for (int i = 0; i < 512; ++i)
        shape[5 + k][513 + i] = shape[5 + k][511 - i];
  }
  // 3. Fold curves.
  std::vector<double> bip(1028), uni(1028);
  double maxB = 0.0, maxU = 0.0;
  for (int i = 0; i < 1028; ++i) {
    double x = i / 512.0 - 1.0;
    if (i == 1027)
      x = 1026 / 512.0 - 1.0;
    double window = std::exp(-x * x * 4.0);
    window *= window;
    bip[i] =
        std::sin(8.0 * kPi * x) * window + std::atan(3.0 * x) * (1.0 - window);
    maxB = std::max(maxB, std::fabs(bip[i]));
    double u = i / 1024.0;
    if (i >= 1026)
      u = 1025 / 1024.0;
    double w2 = std::exp(-u * u * 4.0);
    w2 *= w2;
    uni[i] = (0.38 * std::sin(16.0 * kPi * u) + 4.0 * u) * w2 +
             std::atan(4.0 * u) * (1.0 - w2);
    maxU = std::max(maxU, std::fabs(uni[i]));
  }
  for (int i = 0; i < 1028; ++i) {
    bip[i] /= maxB;
    uni[i] /= maxU;
  }

  fprintf(f, "/**\n * Slope's twelve shape curves, 1025 points each.\n"
             " * Tables 0-4: monotonic audio-rate shapers. Tables 5-11: "
             "control-rate\n * rise-then-fall curves (log, inverse sine, "
             "linear, sine, expo).\n * Returns a pointer to rows of 1025 "
             "floats: lutSlopeShape()[table][i].\n */\n"
             "inline const float (*lutSlopeShape())[1025] {\n"
             "  static const float kTable[12][1025] = {\n");
  for (int k = 0; k < 12; ++k) {
    fprintf(f, "      {\n");
    writeValues(f, shape[k], "      ");
    fprintf(f, "      },\n");
  }
  fprintf(f, "  };\n  return kTable;\n}\n\n");
  writeTable(f, "/** Bipolar fold curve for looping mode (1028 entries). */",
             "lutSlopeBipolarFold", bip);
  writeTable(f, "/** Unipolar fold curve for envelope modes (1028 entries). */",
             "lutSlopeUnipolarFold", uni);
  closeHeader(f);
}

} // namespace

int main(int argc, char **argv) {
  if (argc != 2) {
    fprintf(stderr, "usage: %s <path to src/buddhabox>\n", argv[0]);
    return 1;
  }
  std::string dir = argv[1];
  writeSine(dir);
  writeLuts(dir);
  writeWavefolder(dir);
  writeSlope(dir);
  printf("tables written to %s\n", dir.c_str());
  return 0;
}
