#!/usr/bin/env python3
"""Turn an easel_matrix presets.json into presets.h.

Usage (from the repository root):
    python3 tools/gen_presets.py examples/easel_matrix/presets.json

docs/easel.html saves presets.json; this writes presets.h next to it,
which examples/easel_matrix/main.cpp includes. Never edit presets.h by
hand: edit the JSON (or the page) and run this again.

PRESET FORMAT:
    {"presets": [
      {"name": "Bongo",                     shown on the OLED: 20 chars
       "settings": {"RATE": 60, "GATE_A": 1},   menu values, by item
       "cables": [{"from": "SEQ", "to": "PITCH", "amount": 1.0}],
       "knobs": ["NOISE", "TIMBRE", ...]}   8 items, PA1 to PB0
    ]}
- Items left out of "settings" keep the defaults in main.cpp's menu.
- "from" is a source (PULSER, ENV, SEQ, RANDOM, MOD, CHAOS); "to" is
  an item. "amount" is -1 to 1.

HOW THE NAMES ARE CHECKED: the item and source names are read from the
`enum Item` and `enum Source` blocks in main.cpp, so this script can't
drift out of step with the C++ (and a name it misses there, the
compiler would reject anyway).

Uses only the Python standard library.
"""

import json
import os
import re
import sys

MAX_CABLES = 16     # kMaxCables in main.cpp
KNOBS = 8           # kKnobCount
NOT_SETTABLE = {"PRESET", "VOLUME", "RANDOMIZE"}
SWITCHES_FROM = "MOD_WAVE"  # this item and those after it can't be patched


def read_enum(source, name):
    """Return the names in `enum <name> { ... };`, minus the kCount."""
    match = re.search(r"enum %s \{(.*?)\};" % name, source, re.S)
    if not match:
        sys.exit("error: no enum %s in main.cpp" % name)
    body = re.sub(r"//[^\n]*", "", match.group(1))
    names = [n.strip() for n in body.split(",") if n.strip()]
    return [n for n in names if not n.startswith("k")]


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    path = sys.argv[1]
    folder = os.path.dirname(os.path.abspath(path))
    with open(os.path.join(folder, "main.cpp")) as f:
        cpp = f.read()
    items = read_enum(cpp, "Item")
    sources = [s[len("SRC_"):] for s in read_enum(cpp, "Source")]
    patchable = items[:items.index(SWITCHES_FROM)]
    patchable = [i for i in patchable if i not in NOT_SETTABLE]

    with open(path) as f:
        presets = json.load(f)["presets"]
    if not presets:
        sys.exit("error: no presets")

    # 1. Check every name, and write each preset as a C++ initialiser.
    blocks = []
    for p in presets:
        name = p["name"]
        where = "preset %r" % name

        settings = []
        for item, value in p.get("settings", {}).items():
            if item not in items or item in NOT_SETTABLE:
                sys.exit("error: %s: can't set %r" % (where, item))
            settings.append("{%s, %d}" % (item, int(value)))

        cables = []
        for c in p.get("cables", []):
            if c["from"] not in sources:
                sys.exit("error: %s: no source %r" % (where, c["from"]))
            if c["to"] not in patchable:
                sys.exit("error: %s: can't patch to %r" % (where, c["to"]))
            amount = max(-1.0, min(1.0, float(c["amount"])))
            cables.append("{SRC_%s, %s, %.3ff}" % (c["from"], c["to"],
                                                   amount))
        if len(cables) > MAX_CABLES:
            sys.exit("error: %s: %d cables, at most %d"
                     % (where, len(cables), MAX_CABLES))

        knobs = p.get("knobs", [])
        if len(knobs) != KNOBS or any(k not in patchable for k in knobs):
            sys.exit("error: %s: knobs must be %d of %s"
                     % (where, KNOBS, ", ".join(patchable)))

        # C++ doesn't allow an empty {} for an array of structs inside an
        # aggregate in every case, so an empty list gets one zeroed entry
        # (its count stays 0, so it's never read).
        blocks.append(
            "    {%s,\n     {%s},\n     %d,\n     {%s},\n     %d,\n"
            "     {%s}}" % (
                json.dumps(name[:20]),
                ", ".join(settings) or "{0, 0}", len(settings),
                ", ".join(cables) or "{0, 0, 0.0f}", len(cables),
                ", ".join(knobs)))

    # 2. Write the header.
    out = os.path.join(folder, "presets.h")
    names = ", ".join(json.dumps(p["name"][:20]) for p in presets)
    with open(out, "w") as f:
        f.write("// Generated by tools/gen_presets.py from %s.\n"
                "// Do not edit: edit the JSON (or docs/easel.html) and run"
                " the script again.\n"
                "// clang-format off\n"
                "#pragma once\n\n"
                "const Preset kPresets[] = {\n%s,\n};\n"
                "const int kPresetCount = %d;\n"
                "const char *const kPresetNames[] = {%s};\n"
                % (os.path.basename(path), ",\n".join(blocks), len(presets),
                   names))
    print("wrote %s: %d presets" % (out, len(presets)))


if __name__ == "__main__":
    main()
